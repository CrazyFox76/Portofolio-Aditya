import { useEffect, useLayoutEffect, useRef, useState } from "react";
import { useLanguage } from "../i18n/LanguageContext";

/*
 * One long sticky section, choreographed by scroll progress p (0..1), with timings measured on the
 * wahba site:
 *   0.015-0.10  statement fades out
 *   0.07-0.125  the four inline icons fly to the capability slots and grow
 *   0.125-0.255 capability copy fades in (staggered), holds, fades out
 *   0.25-0.33   icons shrink into the ADITYA column, flipping to their letter faces; definitions fade in
 *   0.45-0.575  background goes dark, the two question letters glow, the rest dims
 *   0.62-0.72   definitions leave; the two question letters grow into the What/How slots
 *   0.72-0.825  background returns to light; "What?" / "How" wipe in
 *   0.88-0.95   the "Let's build" / "and" prefixes open up
 */

// Statement icons: free-standing HD cutouts (no tile) with a periodic glare sweep.
const FRONT = [
	{ src: "/icons/statement/chef.webp", pixel: true, tilt: -5 },
	{ src: "/icons/statement/terminal.webp", tilt: 5 },
	{ src: "/icons/statement/doge.webp", pixel: true, tilt: 4 },
	{ src: "/icons/statement/dino.webp", pixel: true, tilt: -4 },
];
const LETTERS = ["A", "D", "I", "T", "Y", "A"];
// 3D letter tiles (generated by Aditya, background removed): aqua jelly tiles with orange letters, black with white.
const LETTER_IMG = ["a1", "d", "i", "t", "y", "a2"].map((k) => `/icons/letters/${k}.webp`);
const QUESTION_LETTERS = [0, 2]; // A -> What, I -> How
const GLOW = ["255,170,80", "90,200,255"];
const DARK_ROW_COLOR = ["#ffe3bd", "#d6f1ff"];

const clamp = (v) => Math.min(1, Math.max(0, v));
const ease = (t) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);
const seg = (p, a, b) => ease(clamp((p - a) / (b - a)));
const lerp = (a, b, t) => a + (b - a) * t;
const lerpRect = (a, b, t) => ({ x: lerp(a.x, b.x, t), y: lerp(a.y, b.y, t), w: lerp(a.w, b.w, t) });
const mixHex = (a, b, t) => {
	const pa = a.match(/\w\w/g).map((h) => parseInt(h, 16));
	const pb = b.match(/\w\w/g).map((h) => parseInt(h, 16));
	return `rgb(${pa.map((v, i) => Math.round(lerp(v, pb[i], t))).join(",")})`;
};

function FrontTile({ i }) {
	const { src, pixel } = FRONT[i];
	return (
		<span className="shine-art" style={{ "--art": `url(${src})` }}>
			<img src={src} alt="" className={`shine-img${pixel ? " shine-img--pixel" : ""}`} draggable="false" />
			<span className="shine-glare" style={{ animationDelay: `${i * 0.45}s` }} aria-hidden="true" />
		</span>
	);
}
function LetterTile({ i }) {
	return <img className="letter-tile-img" src={LETTER_IMG[i]} alt={LETTERS[i]} draggable="false" />;
}

function useReducedMotionFlag() {
	const [reduced, setReduced] = useState(false);
	useEffect(() => {
		const mq = window.matchMedia("(prefers-reduced-motion: reduce)");
		const set = () => setReduced(mq.matches);
		set();
		mq.addEventListener("change", set);
		return () => mq.removeEventListener("change", set);
	}, []);
	return reduced;
}

export default function BrandStory() {
	const { t, lang } = useLanguage();
	const reduced = useReducedMotionFlag();
	const story = t("brand");

	const secRef = useRef(null);
	const stageRef = useRef(null);
	const stmtRef = useRef(null);
	const stmtSlots = useRef([]);
	const capSlots = useRef([]);
	const capCopy = useRef([]);
	const nameSlots = useRef([]);
	const nameDefs = useRef([]);
	const qSlots = useRef([]);
	const qBase = useRef([]);
	const qPrefix = useRef([]);
	const fly = useRef([]);
	const flip = useRef([]);
	const emitters = useRef([]);
	const rects = useRef(null);

	useLayoutEffect(() => {
		if (reduced) return undefined;
		const stage = stageRef.current;
		let raf = 0;

		const measure = () => {
			const s = stage.getBoundingClientRect();
			const r = (el) => {
				const b = el.getBoundingClientRect();
				return { x: b.left - s.left, y: b.top - s.top, w: b.width };
			};
			rects.current = {
				stmt: stmtSlots.current.map(r),
				cap: capSlots.current.map(r),
				name: nameSlots.current.map(r),
				q: qSlots.current.map(r),
				prefix: qPrefix.current.map((el) => el.firstElementChild.scrollWidth),
			};
		};

		// Displayed progress eases towards the scroll position each frame, so fast scrolling still animates smoothly.
		let shown = null;
		const SMOOTHING = 0.085;

		const render = () => {
			raf = 0;
			const sec = secRef.current;
			const R = rects.current;
			if (!R) return;
			const top = sec.getBoundingClientRect().top;
			const target = clamp(-top / (sec.offsetHeight - window.innerHeight));
			shown = shown === null ? target : shown + (target - shown) * SMOOTHING;
			if (Math.abs(target - shown) < 0.0004) shown = target;
			else raf = requestAnimationFrame(render);
			const p = shown;

			// Background: light -> dark -> light.
			const dark = seg(p, 0.45, 0.575) * (1 - seg(p, 0.72, 0.825));
			const bg = mixHex("fafafa", "06090e", dark);
			stage.style.background = bg;
			sec.style.background = bg;

			stmtRef.current.style.opacity = (1 - 0.88 * seg(p, 0.015, 0.07)) * (1 - seg(p, 0.07, 0.1));

			capCopy.current.forEach((el, i) => {
				el.style.opacity = seg(p, 0.125 + 0.012 * i, 0.165 + 0.012 * i) * (1 - seg(p, 0.24, 0.255));
			});

			const dim = seg(p, 0.45, 0.55);
			const leave = seg(p, 0.62, 0.65);
			nameDefs.current.forEach((el, i) => {
				const qi = QUESTION_LETTERS.indexOf(i);
				const shown = seg(p, 0.28 + 0.008 * i, 0.33);
				// On the dark background all rows turn light (as on wahba); the two question rows also glow.
				el.style.opacity = shown * 1 * (1 - leave);
				el.firstElementChild.style.color = mixHex("1d1d1f", qi >= 0 ? DARK_ROW_COLOR[qi].slice(1) : "e9ebef", dim);
				el.lastElementChild.style.color = mixHex("77777b", "9ba3ae", dim);
				el.firstElementChild.style.textShadow =
					qi >= 0 && dim > 0.01 ? `0 0 ${(18 * dim).toFixed(1)}px rgba(${GLOW[qi]},${(0.55 * dim).toFixed(2)})` : "";
			});

			const toCap = seg(p, 0.07, 0.125);
			const toName = seg(p, 0.25, 0.33);
			const toQuestion = seg(p, 0.65, 0.72);
			const flipT = seg(p, 0.25, 0.32);

			fly.current.forEach((el, i) => {
				let rect;
				let opacity = 1;
				let rot = 0;
				const qi = QUESTION_LETTERS.indexOf(i);
				if (i < 4) {
					rect = lerpRect(lerpRect(R.stmt[i], R.cap[i], toCap), R.name[i], toName);
					rot = FRONT[i].tilt * (1 - toName);
					flip.current[i].style.transform = `rotateY(${(flipT * 180).toFixed(1)}deg)`;
				} else {
					rect = R.name[i];
					opacity = seg(p, 0.29, 0.33);
				}
				if (qi >= 0) {
					rect = lerpRect(rect, R.q[qi], toQuestion);
					const glow = dark;
					// Two-layer glow (tight core + wide bloom) to match wahba's lit W/H tiles on the dark stage.
					el.style.filter =
						glow > 0.01
							? `drop-shadow(0 0 ${(16 * glow).toFixed(1)}px rgba(${GLOW[qi]},${(0.95 * glow).toFixed(2)})) drop-shadow(0 0 ${(70 * glow).toFixed(1)}px rgba(${GLOW[qi]},${(0.75 * glow).toFixed(2)}))`
							: "";
				} else {
					opacity *= 1 - seg(p, 0.62, 0.66);
				}
				el.style.opacity = opacity;
				el.style.width = `${rect.w}px`;
				el.style.height = `${rect.w}px`;
				el.style.fontSize = `${rect.w}px`;
				el.style.transform = `translate3d(${rect.x}px, ${rect.y}px, 0) rotate(${rot}deg)`;

				if (qi >= 0) {
					const em = emitters.current[qi];
					em.style.left = `${rect.x + rect.w / 2}px`;
					em.style.top = `${rect.y + rect.w / 2}px`;
					em.style.opacity = seg(p, 0.47, 0.55) * (1 - seg(p, 0.72, 0.825));
				}
			});

			const wipe = seg(p, 0.72, 0.8);
			const open = seg(p, 0.88, 0.95);
			qBase.current.forEach((el, i) => {
				el.style.opacity = p >= 0.715 ? 1 : 0;
				el.style.clipPath = `inset(0 ${(100 - 100 * wipe).toFixed(1)}% 0 0)`;
				el.parentElement.style.color = mixHex("f0f3f7", "1d1d1f", wipe);
				const pre = qPrefix.current[i];
				pre.style.width = `${(R.prefix[i] * open).toFixed(1)}px`;
				pre.style.opacity = open;
			});
		};

		const schedule = () => {
			if (!raf) raf = requestAnimationFrame(render);
		};
		const remeasure = () => {
			measure();
			schedule();
		};

		remeasure();
		document.fonts?.ready.then(remeasure);
		window.addEventListener("scroll", schedule, { passive: true });
		window.addEventListener("resize", remeasure);
		return () => {
			cancelAnimationFrame(raf);
			window.removeEventListener("scroll", schedule);
			window.removeEventListener("resize", remeasure);
		};
	}, [reduced, lang]);

	let iconIndex = 0;
	return (
		<section
			id="identity"
			ref={secRef}
			className="brand-story-sequence"
			aria-labelledby="brand-intro-title"
			data-reduced={reduced ? "" : undefined}
		>
			<div ref={stageRef} className="brand-story-stage">
				<div className="brand-scene-light" aria-hidden="true">
					<div ref={(el) => (emitters.current[0] = el)} className="brand-emitter-pool brand-emitter-a" />
					<div ref={(el) => (emitters.current[1] = el)} className="brand-emitter-pool brand-emitter-b" />
				</div>

				<h2 id="brand-intro-title" ref={stmtRef} className="brand-intro-statement">
					{story.statement.map((line, li) => (
						<span className="brand-intro-line" key={li}>
							{line.map((tok, ti) => {
								if (tok === "@icon") {
									const idx = iconIndex++;
									return (
										<span
											key={ti}
											ref={(el) => (stmtSlots.current[idx] = el)}
											className="brand-icon-placeholder"
											aria-hidden="true"
										/>
									);
								}
								const bold = tok.startsWith("**");
								const word = bold ? tok.slice(2) : tok;
								return (
									<span key={ti}>
										{bold ? <b className="brand-intro-word">{word}</b> : <span className="brand-intro-word">{word}</span>}{" "}
									</span>
								);
							})}
						</span>
					))}
				</h2>

				<section className="brand-capabilities-row" aria-label={story.capabilitiesLabel}>
					{story.capabilities.map((c, i) => (
						<article className="brand-capability" key={c.title}>
							<div className="brand-capability-slot" ref={(el) => (capSlots.current[i] = el)}>
								{reduced && (
									<span className="block h-full w-full" style={{ fontSize: "clamp(140px, 15vw, 250px)" }}>
										<FrontTile i={i} />
									</span>
								)}
							</div>
							<div className="brand-capability-copy" ref={(el) => (capCopy.current[i] = el)}>
								<h3>{c.title}</h3>
								<p>{c.text}</p>
							</div>
						</article>
					))}
				</section>

				<section className="brand-name-panel" aria-label={story.nameLabel}>
					{story.name.map((row, i) => (
						<div className="brand-name-row" key={i}>
							<div className="brand-name-slot" ref={(el) => (nameSlots.current[i] = el)}>
								{reduced && (
									<span className="block h-full w-full" style={{ fontSize: "clamp(46px, 9svh, 100px)" }}>
										<LetterTile i={i} />
									</span>
								)}
							</div>
							<div className="brand-name-definition" ref={(el) => (nameDefs.current[i] = el)}>
								<h3>{row.title}</h3>
								<p>{row.text}</p>
							</div>
						</div>
					))}
				</section>

				<section className="brand-questions-panel" aria-label={story.questionsLabel}>
					{story.questions.map((q, i) => (
						<div className="brand-question-row" key={i}>
							<div className="brand-question-slot" ref={(el) => (qSlots.current[i] = el)} />
							<div className="brand-question-copy">
								<h3 className={`brand-question-word${i === 0 ? " brand-question-what" : ""}`} aria-label={q.label}>
									<span
										ref={(el) => (qPrefix.current[i] = el)}
										className={`brand-question-prefix${i === 0 ? " brand-question-prefix-what" : ""}`}
									>
										<span>{q.prefix}</span>
									</span>
									<span ref={(el) => (qBase.current[i] = el)} className="brand-question-base">
										{q.base}
									</span>
								</h3>
							</div>
						</div>
					))}
				</section>

				{!reduced && (
					<div className="brand-fly-layer" aria-hidden="true">
						{LETTERS.map((_, i) => (
							<div key={i} ref={(el) => (fly.current[i] = el)} className="brand-fly" style={{ opacity: 0, perspective: "700px" }}>
								<div className="brand-fly-flip" ref={(el) => (flip.current[i] = el)}>
									{i < 4 ? (
										<>
											<span className="brand-fly-face">
												<FrontTile i={i} />
											</span>
											<span className="brand-fly-face brand-fly-face--back">
												<LetterTile i={i} />
											</span>
										</>
									) : (
										<span className="brand-fly-face">
											<LetterTile i={i} />
										</span>
									)}
								</div>
							</div>
						))}
					</div>
				)}
			</div>
		</section>
	);
}
